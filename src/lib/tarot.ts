import type { OracleCard } from './divination';

export interface TarotCard extends OracleCard {
  arcana: 'major' | 'minor';
  suit?: 'swords' | 'cups' | 'pentacles' | 'wands';
  keywords: string[];
}

const SUIT_ICON = {
  swords: 'Swords',
  cups: 'Wine',
  pentacles: 'Coins',
  wands: 'Flame',
} as const;

export const SUIT_NAMES = {
  swords: 'Мечи',
  cups: 'Кубки',
  pentacles: 'Пентакли',
  wands: 'Жезлы',
} as const;

const major = (
  name: string,
  icon: string,
  keyword: string,
  keywords: string[],
  message: string,
  advice: string,
): TarotCard => ({ arcana: 'major', name, icon, keyword, keywords, message, advice });

const minor = (
  suit: keyof typeof SUIT_ICON,
  name: string,
  keyword: string,
  keywords: string[],
  message: string,
  advice: string,
): TarotCard => ({
  arcana: 'minor',
  suit,
  name,
  icon: SUIT_ICON[suit],
  keyword,
  keywords,
  message,
  advice,
});

