const MOOD_FEMININE: Record<string, string> = {
  тревожный: 'настороженная',
  светлый: 'тёплая и ясная',
  печальный: 'тихая и грустная',
  загадочный: 'туманная',
  нейтральный: 'ровная',
};

export interface Interpretation {
  mood: string;
  symbols: DreamSymbol[];
  text: string;
}

export const interpretDream = (input: string): Interpretation => {
  const text = input.toLowerCase();

  const found = SYMBOLS.filter((symbol) => symbol.keywords.some((word) => text.includes(word)));
  const symbols = found.length ? found.slice(0, 3) : [SYMBOLS[(input.length + 3) % SYMBOLS.length]];

  const mood =
    MOODS.find((m) => m.words.some((w) => text.includes(w)))?.key ?? 'нейтральный';

  const opener = OPENERS[input.length % OPENERS.length];

  const body = symbols
    .map((s) => `«${s.title}» — ${s.meaning}`)
    .join('\n\n');

  const bridge = found.length
    ? `Вместе эти образы складываются в ${mood} сюжет о переходе: старое уже не держит, новое ещё не названо.`
    : `Явных архетипов немного, поэтому Морфей читает сон по общей интонации — она ${MOOD_FEMININE[mood]}.`;

  return {
    mood,
    symbols,
    text: `${opener}\n\n${body}\n\n${bridge}\n\n${CLOSERS[mood] ?? CLOSERS['нейтральный']}`,
  };
};